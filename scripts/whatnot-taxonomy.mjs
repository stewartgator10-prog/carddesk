#!/usr/bin/env node
// Regenerates netlify/lib/marketplaces/whatnot-taxonomy.js from Whatnot's published product
// taxonomy (docs/marketplaces/whatnot-api/taxonomy.json, from github.com/Whatnot-Inc/product-taxonomy).
// Keeps only the trading card game categories and the card details we can fill in, so the app never
// loads the whole 450 KB file.
//
//   node scripts/whatnot-taxonomy.mjs [path/to/taxonomy.json]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.resolve(process.argv[2] || path.join(root, 'docs/marketplaces/whatnot-api/taxonomy.json'));
const out = path.join(root, 'netlify/lib/marketplaces/whatnot-taxonomy.js');

const TCG_PARENT_TYPE = 'trading_card_games';
const SKIP_TYPES = new Set(['tcg_accessories']);   // not single cards

// What a card detail is, from the attribute key. Anything else (features, card type, autographed) is left out.
export function roleOf(key) {
  const k = String(key).trim();
  if (k === 'tcg.condition') return 'condition';
  if (k === 'graded' || /\.graded$/.test(k)) return 'graded';
  if (k === 'graded.service' || /\.grading_service$/.test(k)) return 'grading_service';
  if (k === 'graded.grade' || /\.grade$/.test(k)) return 'grade';
  if (k === 'graded.cert_number' || /\.cert_number$/.test(k)) return 'cert';
  if (/card_number$/.test(k)) return 'card_number';
  if (/\.(card_set|set)$/.test(k)) return 'set';
  if (/\.language$/.test(k)) return 'language';
  if (/\.rarity$/.test(k)) return 'rarity';
  if (/\.product_type$/.test(k)) return 'product_type';
  return null;
}
// Free-text details whose suggested values are worth keeping (to use Whatnot's own spelling).
const KEEP_SUGGESTIONS = new Set(['rarity', 'grading_service', 'grade']);

const tax = JSON.parse(fs.readFileSync(src, 'utf8'));
const parent = tax.categories.find((c) => c.type === TCG_PARENT_TYPE);
if (!parent) throw new Error(`No "${TCG_PARENT_TYPE}" category in ${src}`);
const attrById = new Map(tax.attributes.map((a) => [a.id, a]));

const categories = [];
const attributes = {};
for (const c of tax.categories.filter((x) => x.parent_id === parent.id && !SKIP_TYPES.has(x.type) && x.allows_inventory !== false).sort((a, b) => a.id - b.id)) {
  const attrs = {};
  for (const ref of c.attributes || []) {
    const a = attrById.get(ref.id);
    const role = a && roleOf(a.key);
    if (!role || attrs[role]) continue;
    attrs[role] = a.id;
    const keepValues = a.type === 'ENUM' || (a.allows_custom_values && KEEP_SUGGESTIONS.has(role));
    attributes[a.id] = { key: a.key.trim(), type: a.type, custom: !!a.allows_custom_values, ...(keepValues && a.values?.length ? { values: a.values } : {}), ...(ref.is_required ? { required: true } : {}) };
  }
  categories.push({ id: c.id, type: c.type, label: c.label, attrs });
}

const body = `// netlify/lib/marketplaces/whatnot-taxonomy.js
// GENERATED by scripts/whatnot-taxonomy.mjs from docs/marketplaces/whatnot-api/taxonomy.json
// (Whatnot product taxonomy ${tax.version}). Do not edit by hand: change the script and run it again.
// Trading card game categories under "${parent.label}" (${parent.id}), and the card details each one
// takes, by what they mean (condition, set, card_number, language, rarity, product_type, graded,
// grading_service, grade, cert) -> attribute id.
export const TAXONOMY_VERSION = ${JSON.stringify(tax.version)};
export const TCG_PARENT_ID = ${parent.id};
export const TCG_CATEGORIES = ${JSON.stringify(categories, null, 0).replace(/\},\{"id"/g, '},\n  {"id"').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};
export const TCG_ATTRIBUTES = {
${Object.entries(attributes).sort((a, b) => a[0] - b[0]).map(([id, a]) => `  ${id}: ${JSON.stringify(a)},`).join('\n')}
};
`;
fs.writeFileSync(out, body);
console.log(`wrote ${path.relative(root, out)}: ${categories.length} categories, ${Object.keys(attributes).length} attributes (taxonomy ${tax.version})`);
